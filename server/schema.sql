CREATE TABLE IF NOT EXISTS totals (
  id INTEGER PRIMARY KEY CHECK(id=1), players INTEGER NOT NULL DEFAULT 0,
  runs INTEGER NOT NULL DEFAULT 0, b0 INTEGER NOT NULL DEFAULT 0, b1 INTEGER NOT NULL DEFAULT 0,
  b2 INTEGER NOT NULL DEFAULT 0, b3 INTEGER NOT NULL DEFAULT 0, b4 INTEGER NOT NULL DEFAULT 0,
  b5 INTEGER NOT NULL DEFAULT 0, b6 INTEGER NOT NULL DEFAULT 0, b7 INTEGER NOT NULL DEFAULT 0,
  updated INTEGER NOT NULL DEFAULT 0
);
INSERT OR IGNORE INTO totals(id) VALUES(1);
CREATE TABLE IF NOT EXISTS players (
  id TEXT PRIMARY KEY, last_batch TEXT NOT NULL, last_at INTEGER NOT NULL,
  day INTEGER NOT NULL, runs INTEGER NOT NULL, batches INTEGER NOT NULL
) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS limits (
  id TEXT PRIMARY KEY, day INTEGER NOT NULL, batches INTEGER NOT NULL
) WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS limits_day ON limits(day);
CREATE TABLE IF NOT EXISTS submissions (
  id TEXT PRIMARY KEY, player TEXT NOT NULL, ip TEXT NOT NULL, day INTEGER NOT NULL,
  at INTEGER NOT NULL, runs INTEGER NOT NULL CHECK(runs BETWEEN 1 AND 20),
  b0 INTEGER NOT NULL, b1 INTEGER NOT NULL, b2 INTEGER NOT NULL, b3 INTEGER NOT NULL,
  b4 INTEGER NOT NULL, b5 INTEGER NOT NULL, b6 INTEGER NOT NULL, b7 INTEGER NOT NULL,
  CHECK(b0+b1+b2+b3+b4+b5+b6+b7=runs)
) WITHOUT ROWID;
CREATE TRIGGER IF NOT EXISTS submission_guard BEFORE INSERT ON submissions BEGIN
  SELECT CASE WHEN
    COALESCE((SELECT batches FROM limits WHERE id='global' AND day=NEW.day),0)>=4000
    OR COALESCE((SELECT batches FROM limits WHERE id=NEW.ip AND day=NEW.day),0)>=120
    OR EXISTS(SELECT 1 FROM players WHERE id=NEW.player AND
      (last_at>NEW.at-60 OR last_batch=NEW.id OR (day=NEW.day AND (runs+NEW.runs>240 OR batches>=60))))
    THEN RAISE(IGNORE) END;
END;
CREATE TRIGGER IF NOT EXISTS submission_apply AFTER INSERT ON submissions BEGIN
  UPDATE totals SET players=players+CASE WHEN EXISTS(SELECT 1 FROM players WHERE id=NEW.player) THEN 0 ELSE 1 END,
    runs=runs+NEW.runs, b0=b0+NEW.b0, b1=b1+NEW.b1, b2=b2+NEW.b2, b3=b3+NEW.b3,
    b4=b4+NEW.b4, b5=b5+NEW.b5, b6=b6+NEW.b6, b7=b7+NEW.b7, updated=NEW.at WHERE id=1;
  INSERT INTO players VALUES(NEW.player,NEW.id,NEW.at,NEW.day,NEW.runs,1)
    ON CONFLICT(id) DO UPDATE SET last_batch=NEW.id,last_at=NEW.at,day=NEW.day,
      runs=CASE WHEN players.day=NEW.day THEN players.runs+NEW.runs ELSE NEW.runs END,
      batches=CASE WHEN players.day=NEW.day THEN players.batches+1 ELSE 1 END;
  INSERT INTO limits VALUES('global',NEW.day,1) ON CONFLICT(id) DO UPDATE SET day=NEW.day,
    batches=CASE WHEN limits.day=NEW.day THEN limits.batches+1 ELSE 1 END;
  INSERT INTO limits VALUES(NEW.ip,NEW.day,1) ON CONFLICT(id) DO UPDATE SET day=NEW.day,
    batches=CASE WHEN limits.day=NEW.day THEN limits.batches+1 ELSE 1 END;
  DELETE FROM submissions WHERE id=NEW.id;
  DELETE FROM limits WHERE id IN (SELECT id FROM limits WHERE day<NEW.day-1 LIMIT 4);
END;
